OZET = ("Law no. 7589, in force since 31 July 2026, amended article 114 of the Enforcement and "
        "Bankruptcy Law and introduced a new procedure for auctions dissolving co-ownership by sale. "
        "For property acquired by inheritance, the first auction is held among the co-owning heirs "
        "alone, and the bid threshold in that auction is the full appraised value. The change does "
        "not apply to auctions already advertised before it took effect.")

