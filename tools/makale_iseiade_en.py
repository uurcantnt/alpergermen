   "Article 20 allocates the burden of proof expressly.",
   "The obligation to prove that the termination rested on a valid reason lies with the employer, who "
   "must establish both the reason relied on and its validity.",
   "Where the employee alleges that the termination rested on some other reason, the employee bears "
   "the burden of proving that allegation. If it is said that the termination was for union reasons or "
