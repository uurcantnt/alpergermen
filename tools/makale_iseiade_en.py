 ("Who may bring a reinstatement claim?", [
   "Article 18 of the Labour Code identifies the employee who benefits from job security by three "
   "criteria.",
   "The first concerns the workplace: thirty or more employees must be employed there. The figure is "
   "determined on the basis of all employees working at the employer's workplaces in the same branch "
   "of activity.",
   "The second concerns service: the employee must have at least six months' service. The periods in "
   "article 66 of the Code count towards that calculation. No service requirement applies to employees "
   "working underground.",
   "The third concerns the contract: it must be of indefinite duration. Where a fixed-term contract "
   "ends on expiry of its term, no reinstatement claim may be brought.",
   "Unless all three conditions are met the claim will not be heard, and the employee's claims fall to "
   "be assessed under other heads such as bad-faith compensation and notice pay."]),

 ("What is a valid reason, and what is not?", [
   "An employer terminating a contract of indefinite duration must rely on a valid reason arising from "
   "the employee's capability or conduct, or from the requirements of the undertaking, the workplace "
   "or the work.",
   "The Code separately lists situations that do not constitute a valid reason. Trade union membership, "
   "and participation in union activities outside working hours or, with the employer's consent, "
   "during working hours, are not valid reasons.",
   "Acting as a workplace union representative; and applying to administrative or judicial authorities "
   "against the employer, or taking part in proceedings so commenced, in order to pursue rights or "
   "perform obligations arising from legislation or contract, are likewise not valid reasons.",
   "Race, colour, sex, marital status, family responsibilities, pregnancy, childbirth, religion, "
   "political opinion and similar grounds are on the list, as is absence during the periods in article "
   "74 in which the employment of women is prohibited."]),

 ("Procedure on termination: written notice and a hearing", [
   "Article 19 imposes two requirements as to the form of termination.",
   "The first is writing: the employer must give the notice of termination in writing and state the "
   "reason clearly and definitely. As a rule the reason may not later be changed or expanded.",
   "The second is the employee's defence: the contract of indefinite duration of an employee may not be "
   "terminated for reasons connected with that employee's conduct or performance without first taking "
   "their defence to the allegations.",
   "The exception is that the employer's right to terminate under article 25(II) is reserved. Where "
   "termination is for just cause based on conduct contrary to morality and good faith, no defence "
   "need be taken."]),

 ("The first period: one month to apply to a mediator", [
   "The first step is not litigation but mediation, and it is a condition precedent to proceedings.",
   "An employee whose contract has been terminated must apply to a mediator seeking reinstatement, "
   "within one month of service of the notice of termination, on the ground that no reason was given "
   "or that the reason given is not valid.",
   "Under article 3 of Labour Courts Act no. 7036, applying to a mediator is a condition precedent in "
   "claims seeking reinstatement. Where it emerges that proceedings were issued without such an "
   "application, the claim is dismissed on procedural grounds without any further step.",
   "Time runs not from the date of termination but from service of the notice. Documenting when and "
   "how the notice was served is therefore important."]),

